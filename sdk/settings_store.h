using Key=std::pair<std::wstring,std::wstring>;
using Values=std::map<Key,std::wstring>;
inline std::wstring lower(std::wstring s){for(auto& c:s)c=wchar_t(towlower(c));return s;}
inline std::wstring overrides(const std::wstring& dir){return dir+L"\\settings.overrides.ini";}
inline std::wstring effective(const std::wstring& dir){return dir+L"\\.settings.effective.ini";}
struct Lock {
    HANDLE handle{};
    explicit Lock(const std::wstring& dir){uint64_t hash=14695981039346656037ull;for(auto c:lower(std::filesystem::absolute(dir).wstring())){hash^=uint16_t(c);hash*=1099511628211ull;}auto name=L"Local\\SWML_settings_"+std::to_wstring(hash);handle=CreateMutexW(nullptr,FALSE,name.c_str());if(!handle)throw std::runtime_error("settings lock unavailable");auto result=WaitForSingleObject(handle,5000);if(result!=WAIT_OBJECT_0&&result!=WAIT_ABANDONED){CloseHandle(handle);handle=nullptr;throw std::runtime_error("settings are busy");}}
    ~Lock(){if(handle){ReleaseMutex(handle);CloseHandle(handle);}}
};
inline Values read(const std::wstring& path){
    Values result;std::vector<wchar_t> sections(65536),entries(65536);
    if(GetPrivateProfileSectionNamesW(sections.data(),DWORD(sections.size()),path.c_str())>=sections.size()-2)throw std::runtime_error("too many settings sections");
    for(const wchar_t* section=sections.data();*section;section+=wcslen(section)+1){
        if(GetPrivateProfileSectionW(section,entries.data(),DWORD(entries.size()),path.c_str())>=entries.size()-2)throw std::runtime_error("settings section too large");
        for(const wchar_t* entry=entries.data();*entry;entry+=wcslen(entry)+1){std::wstring text=entry;auto equal=text.find(L'=');if(equal!=text.npos)result[{lower(section),lower(text.substr(0,equal))}]=text.substr(equal+1);}
    }return result;
}
inline void atomic_write(const std::wstring& path,const Values& values){
    std::wstring text=path.ends_with(L"settings.overrides.ini")?L"; User overrides only. Omitted keys use shipped defaults.\r\n":L"; Generated by SWML. User changes belong in settings.overrides.ini.\r\n";std::wstring section;
    for(const auto& [key,value]:values){if(value.find_first_of(L"\r\n")!=value.npos || value.find(L'\0')!=value.npos)throw std::runtime_error("invalid multiline setting");if(key.first!=section){section=key.first;text+=L"\r\n["+section+L"]\r\n";}text+=key.second+L"="+value+L"\r\n";}
    static LONG serial=0;auto temporary=path+L".tmp."+std::to_wstring(GetCurrentProcessId())+L"."+std::to_wstring(InterlockedIncrement(&serial));
    HANDLE file=CreateFileW(temporary.c_str(),GENERIC_WRITE,0,nullptr,CREATE_NEW,FILE_ATTRIBUTE_NORMAL,nullptr);if(file==INVALID_HANDLE_VALUE)throw std::runtime_error("cannot create settings file");
    WORD bom=0xfeff;DWORD written=0;bool ok=WriteFile(file,&bom,2,&written,nullptr)&&written==2;DWORD bytes=DWORD(text.size()*sizeof(wchar_t));ok=ok&&WriteFile(file,text.data(),bytes,&written,nullptr)&&written==bytes&&FlushFileBuffers(file);CloseHandle(file);
    if(!ok||!MoveFileExW(temporary.c_str(),path.c_str(),MOVEFILE_REPLACE_EXISTING|MOVEFILE_WRITE_THROUGH)){DeleteFileW(temporary.c_str());throw std::runtime_error("cannot commit settings file");}
    WritePrivateProfileStringW(nullptr,nullptr,nullptr,path.c_str());
}
inline Values defaults(const std::wstring& dir){return read(dir+L"\\settings.default.ini");}
inline Values merged(const std::wstring& dir){auto result=defaults(dir);for(const auto& [key,value]:read(overrides(dir)))result[key]=value;return result;}
inline void prepare(const std::wstring& dir){Lock lock(dir);auto base=defaults(dir),changes=read(overrides(dir));bool changed=false;for(auto it=changes.begin();it!=changes.end();)if(auto def=base.find(it->first);def!=base.end()&&def->second==it->second){it=changes.erase(it);changed=true;}else ++it;if(changed||GetFileAttributesW(overrides(dir).c_str())==INVALID_FILE_ATTRIBUTES)atomic_write(overrides(dir),changes);for(const auto& [key,value]:changes)base[key]=value;atomic_write(effective(dir),base);}
inline void set(const std::wstring& dir,std::wstring section,std::wstring key,const std::wstring& value,const std::wstring* fallback=nullptr){
    Lock lock(dir);Key id{lower(section),lower(key)};auto base=defaults(dir),changes=read(overrides(dir));auto found=base.find(id);const std::wstring* initial=found!=base.end()?&found->second:fallback;
    if(initial&&value==*initial)changes.erase(id);else changes[id]=value;
    auto runtime=base;for(const auto& [k,v]:changes)runtime[k]=v;
    // Commit user state first; runtime cache can always be rebuilt on next start.
    atomic_write(overrides(dir),changes);atomic_write(effective(dir),runtime);
}
