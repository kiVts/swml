#pragma once
// Shared loader/core persistence. Defaults are shipped; only deviations are user state.
// OS calls go through swml_platform (Windows: profile APIs + named mutex; POSIX: compatible
// INI parser + flock), so the native Linux launcher and the Proton-hosted core share one format.
#include "../launcher/platform.h"
#include <algorithm>
#include <cwctype>
#include <filesystem>
#include <map>
#include <stdexcept>
#include <string>
#include <vector>
namespace swml_settings_store {
using Key=std::pair<std::wstring,std::wstring>;
using Values=std::map<Key,std::wstring>;
inline std::wstring lower(std::wstring s){for(auto& c:s)c=wchar_t(towlower(c));return s;}
inline std::wstring overrides(const std::wstring& dir){return (std::filesystem::path(dir)/"settings.overrides.ini").wstring();}
inline std::wstring effective(const std::wstring& dir){return (std::filesystem::path(dir)/".settings.effective.ini").wstring();}
struct Lock {
    swml_platform::DirLock lock;
    explicit Lock(const std::wstring& dir):lock(dir){}
};
inline Values read(const std::wstring& path){
    Values result;
    for(const auto& section:swml_platform::ini_sections(path))
        for(const auto& entry:section.entries)result[{lower(section.name),lower(entry.key)}]=entry.value;
    return result;
}
inline void atomic_write(const std::wstring& path,const Values& values){
    std::wstring text=path.ends_with(L"settings.overrides.ini")?L"; User overrides only. Omitted keys use shipped defaults.\r\n":L"; Generated by SWML. User changes belong in settings.overrides.ini.\r\n";
    std::vector<swml_platform::IniKeyValue> items;
    for(const auto& [key,value]:values){
        if(value.find_first_of(L"\r\n")!=value.npos || value.find(L'\0')!=value.npos)throw std::runtime_error("invalid multiline setting");
        items.push_back({key.first,key.second,value});
    }
    swml_platform::ini_write_all(path,text,items);
    swml_platform::ini_flush(path);
}
inline Values defaults(const std::wstring& dir){return read((std::filesystem::path(dir)/"settings.default.ini").wstring());}
inline Values merged(const std::wstring& dir){auto result=defaults(dir);for(const auto& [key,value]:read(overrides(dir)))result[key]=value;return result;}
inline void prepare(const std::wstring& dir){Lock lock(dir);auto base=defaults(dir),changes=read(overrides(dir));bool changed=false;for(auto it=changes.begin();it!=changes.end();)if(auto def=base.find(it->first);def!=base.end()&&def->second==it->second){it=changes.erase(it);changed=true;}else ++it;if(changed||!swml_platform::path_exists(overrides(dir)))atomic_write(overrides(dir),changes);for(const auto& [key,value]:changes)base[key]=value;atomic_write(effective(dir),base);}
inline void set(const std::wstring& dir,std::wstring section,std::wstring key,const std::wstring& value,const std::wstring* fallback=nullptr){
    Lock lock(dir);Key id{lower(section),lower(key)};auto base=defaults(dir),changes=read(overrides(dir));auto found=base.find(id);const std::wstring* initial=found!=base.end()?&found->second:fallback;
    if(initial&&value==*initial)changes.erase(id);else changes[id]=value;
    auto runtime=base;for(const auto& [k,v]:changes)runtime[k]=v;
    // Commit user state first; runtime cache can always be rebuilt on next start.
    atomic_write(overrides(dir),changes);atomic_write(effective(dir),runtime);
}
}
